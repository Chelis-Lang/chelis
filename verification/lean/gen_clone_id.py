"""Generate, or check, the clone-identity theorems of `ChelisBridge/Runtime/CloneId.lean`: for the
derived `Clone` impls a generated model reaches from given root clone functions.

usage: gen_clone_id.py [--check] <model dir> <model roots> <module.lean>

`<model dir>` and `<model roots>` are the lakefile's `model` and `modelRoots` (comma-separated
modules; the modules they import from the same directory are read too), so both model layouts
work: the combined one (`ChelisIr`) and the whole-core chunks (`<Chunk>.Types`, ...). Every
name is read in the spelling the bridge uses in both layouts (`ChelisBridge/Model.lean`), so
the same model yields the same theorems in either layout.

`<module.lean>` keeps everything up to and including its line `MARKER` (the hand-written
library lemmas); its line `ROOTS_PREFIX <names>` above the marker lists the root clone
functions. Everything after the marker is the generated theorems and the closing
`end <namespace>` (the last `namespace` opened above the marker). Without `--check` the module
is rewritten; with `--check` nothing is written and the exit status is 1, with a diff, when
the module differs from what this model generates (a stale module).

For every derived clone function `F` of a type `T` in the closure (in dependency order), emits
`theorem cid_<T> (insts…) (hyps…) : ∀ x : T, F insts… x = .ok x` (generic types take each
parameter's clone instance and the hypothesis that it is the identity). Non-recursive
functions: `cases x <;> simp [F, …]` with the clone lemmas of the library and of earlier
types as conditional simp lemmas. Recursive groups (`partial_fixpoint`, `mutual`): one
`mutual` block of structurally recursive theorems by constructor patterns (every `Option`
field split into `none` / `some`), with helper theorems for the `NestedVec` nests of the
group's types.
"""
import difflib
from pathlib import Path
import re
import sys

MARKER = "-- Generated by gen_clone_id.py below this line; do not edit."
ROOTS_PREFIX = "-- gen_clone_id.py roots:"

# The crate whose items the bridge names `chelis_ir.<path>` (`open_chelis_model`); a combined
# extraction also wraps the foreign items in its namespace.
LOCAL = "chelis_ir"
FOREIGN = ("chelis_types", "chelis_unord", "chelis_deep", "chelis_effects", "chelis_pred",
           "chelis_vocab", "chelis_pipeline_core", "core", "alloc", "half", "std", "serde")

cli = sys.argv[1:]
check = cli[:1] == ["--check"]
if check:
    cli = cli[1:]
if len(cli) != 3:
    raise SystemExit(__doc__)
model_dir, model_roots, out_path = Path(cli[0]), cli[1].split(","), cli[2]


def canon(name: str) -> str:
    """A model name as the bridge spells it in both layouts: the combined layout's
    `chelis_ir.<foreign crate>.<path>` is `<foreign crate>.<path>`."""
    name = name.removeprefix("_root_.")
    if name.startswith(LOCAL + ".") and name[len(LOCAL) + 1:].split(".")[0] in FOREIGN:
        return name[len(LOCAL) + 1:]
    return name


rooted = re.compile(r"_root_\.[A-Za-z_][A-Za-z0-9_'.]*")


def canon_text(s: str) -> str:
    """A type as the bridge spells it: every `_root_`-qualified name canonical."""
    return rooted.sub(lambda m: canon(m.group(0)), s)


# ---------------------------------------------------------------------------------------------
# The model's files: the roots and what they import from the model directory.
files, pending = [], list(model_roots)
while pending:
    module = pending.pop(0)
    path = model_dir / (module.replace(".", "/") + ".lean")
    if path in files:
        continue
    if not path.is_file():
        raise SystemExit(f"no model module {module} ({path})")
    files.append(path)
    for imported in re.findall(r"^import\s+(\S+)", path.read_text(), re.M):
        if (model_dir / (imported.replace(".", "/") + ".lean")).is_file():
            pending.append(imported)

# Top-level blocks of every file: kind, canonical name, text, mutual group id.
blocks = []
mcount = 0
decl_re = re.compile(r"^(?:noncomputable )?(inductive|structure|def|theorem|abbrev)(?:\s+(\S+))?\s*$|"
                     r"^(?:noncomputable )?(inductive|structure|def|theorem|abbrev)\s+(\S+)")


def decl_at(lines, i):
    """(kind, name) of a declaration starting at line `i` (a long name goes on the next line)."""
    m = decl_re.match(lines[i])
    if not m:
        return None
    if m.group(3):
        return m.group(3), m.group(4)
    if m.group(2):
        return m.group(1), m.group(2)
    if i + 1 < len(lines) and lines[i + 1].startswith("  "):
        return m.group(1), lines[i + 1].split()[0]
    return None


for path in files:
    lines = path.read_text().split("\n")
    prefix = ""
    mutual_id = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^namespace\s+(\S+)\s*$", line)
        if m:
            prefix = m.group(1) + "."
            i += 1
            continue
        if line.strip() == "mutual":
            mcount += 1
            mutual_id = mcount
            i += 1
            continue
        if line.strip() == "end" and mutual_id is not None:
            mutual_id = None
            i += 1
            continue
        d = decl_at(lines, i)
        if d:
            j = i + 1
            while j < len(lines) and not decl_at(lines, j) and not lines[j].startswith("/--") \
                    and lines[j].strip() not in ("mutual", "end") and not lines[j].startswith("@[") \
                    and not lines[j].startswith("end "):
                j += 1
            kind, name = d
            name = canon(name if name.startswith("_root_.") else prefix + name)
            blocks.append({"kind": kind, "name": name, "text": "\n".join(lines[i:j]),
                           "mutual": mutual_id, "prefix": prefix})
            i = j
            continue
        i += 1

by_name = {}
for b in blocks:
    by_name.setdefault(b["name"], b)


def body(b) -> str:
    return b["text"]


def split_arrows(s: str):
    parts, depth, cur = [], 0, ""
    k = 0
    while k < len(s):
        c = s[k]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if depth == 0 and s.startswith("→", k):
            parts.append(cur.strip())
            cur = ""
            k += 1
            continue
        cur += c
        k += 1
    parts.append(cur.strip())
    return parts


def parse_type(b):
    """(params, ctors) with ctors = [(ctor name, [field types])]; structures: one ctor `mk`
    with named fields [(field, type)]."""
    lines = b["text"].split("\n")
    head = lines[0]
    params = re.findall(r"\((\w+) : Type\)", head)
    ctors = []
    if b["kind"] == "inductive":
        cur = None
        for line in lines[1:]:
            if line.startswith("| "):
                if cur:
                    ctors.append(cur)
                m = re.match(r"\| (\w+) :(.*)", line)
                cur = [m.group(1), m.group(2)]
            elif cur and line.strip():
                cur[1] += " " + line.strip()
        if cur:
            ctors.append(cur)
        result = []
        for name, ty in ctors:
            parts = split_arrows(ty.strip())
            result.append((name, [(None, p) for p in parts[:-1]]))
        return params, result
    fields = []
    for line in lines[1:]:
        m = re.match(r"^  (\w+) :(.*)", line)
        if m:
            fields.append([m.group(1), m.group(2).strip()])
        elif fields and line.startswith("    "):
            fields[-1][1] += " " + line.strip()
    return params, [("mk", [(f, t) for f, t in fields])]


clone_suffix = ".Insts.CoreCloneClone.clone"
inst_suffix = ".Insts.CoreCloneClone"


def clone_type(fname: str) -> str:
    return fname[: -len(clone_suffix)]


ident = re.compile(r"[A-Za-z_][A-Za-z0-9_'.]*")

module_text = open(out_path).read()
module_lines = module_text.split("\n")
if MARKER not in module_lines:
    raise SystemExit(f"{out_path}: no line {MARKER!r}")
head_lines = module_lines[: module_lines.index(MARKER) + 1]
root_lines = [line for line in head_lines if line.startswith(ROOTS_PREFIX)]
if len(root_lines) != 1:
    raise SystemExit(f"{out_path}: expected one line {ROOTS_PREFIX!r} above the marker")
roots = root_lines[0][len(ROOTS_PREFIX):].split()
namespaces = [m.group(1) for line in head_lines for m in [re.match(r"^namespace\s+(\S+)\s*$", line)] if m]
if not roots or not namespaces:
    raise SystemExit(f"{out_path}: no roots or no namespace above the marker")
LEAN_NS = namespaces[-1]

# closure of clone functions
seen, stack = set(), list(roots)
deps = {}
while stack:
    f = stack.pop()
    if f in seen:
        continue
    if f not in by_name:
        raise SystemExit(f"no definition {f} in the model")
    seen.add(f)
    refs = set()
    prefix = by_name[f]["prefix"]
    for tok in ident.findall(body(by_name[f])):
        # A name inside the combined layout's namespace may be written relative to it.
        for t in ([canon(tok)] if tok.startswith("_root_.") else [canon(prefix + tok), canon(tok)]):
            if t == f:
                break
            if t.endswith(clone_suffix) and t in by_name:
                refs.add(t)
                break
            if t.endswith(inst_suffix) and t + ".clone" in by_name:
                refs.add(t + ".clone")
                break
    deps[f] = refs
    stack.extend(sorted(refs))

# groups: a mutual block, or a single function
group_of = {}
for f in seen:
    b = by_name[f]
    group_of[f] = ("m", b["mutual"]) if b["mutual"] else ("s", f)
groups = {}
for f in seen:
    groups.setdefault(group_of[f], []).append(f)


def group_key(g):
    """Layout-independent order key of a group: its smallest member (mutual ids are numbered
    in file order, which differs between layouts)."""
    return min(groups[g])


# topological order of groups
gdeps = {g: {group_of[d] for f in fs for d in deps[f]} - {g} for g, fs in groups.items()}
ordered, done = [], set()


def visit(g, path=()):
    if g in done:
        return
    if g in path:
        raise SystemExit(f"cycle between groups {path}")
    for d in sorted(gdeps[g], key=group_key):
        visit(d, path + (g,))
    done.add(g)
    ordered.append(g)


for g in sorted(groups, key=group_key):
    visit(g)


def local(name: str) -> str:
    return name.removeprefix(LOCAL + ".")


def thm_name(f: str) -> str:
    return "cid_" + local(clone_type(f)).replace(".", "_")


def fn_params(f: str):
    """Implicit type params and (inst name, type param) of a clone def."""
    head = body(by_name[f]).split(":=")[0]
    tparams = re.findall(r"\{(\w+) : Type\}", head)
    insts = re.findall(r"\((\w+) :\s*_root_\.Aeneas\.Std\.core\.clone\.Clone (\w+)\)", head)
    return tparams, insts


def self_type(f: str) -> str:
    head = body(by_name[f])
    m = re.search(r"\(self :\s*(.*?)\)\s*:\s*\n", head, re.S)
    if not m:
        m = re.search(r"\(self :\s*([^)]*(?:\([^)]*\))?[^)]*)\)", head, re.S)
    return canon_text(" ".join(m.group(1).split()))


def binders(f: str) -> tuple[str, str]:
    tparams, insts = fn_params(f)
    bs = "".join(f" {{{t} : Type}}" for t in tparams)
    args = ""
    for inst, t in insts:
        bs += (f" ({inst} : Aeneas.Std.core.clone.Clone {t})"
               f" (h_{inst} : ∀ y, {inst}.clone y = .ok y)")
        args += f" {inst} h_{inst}"
    return bs, args


def clone_app(f: str) -> str:
    _, insts = fn_params(f)
    return f + "".join(f" {i}" for i, _ in insts)


out = head_lines + [""]
emit = out.append


def type_block(tyname: str):
    b = by_name.get(tyname)
    if b is None:
        raise SystemExit(f"no type {tyname}")
    return b


for g in ordered:
    fs = sorted(groups[g])
    recursive = any("partial_fixpoint" in body(by_name[f]) for f in fs)
    if not recursive:
        for f in fs:
            bs, _ = binders(f)
            ty = self_type(f)
            hyps = ", ".join(f"h_{i}" for i, _ in fn_params(f)[1])
            emit(f"@[simp] theorem {thm_name(f)}{bs} (x : {ty}) :")
            emit(f"    {clone_app(f)} x = .ok x := by")
            emit(f"  cases x <;> simp [{f}{', ' + hyps if hyps else ''}] <;> rfl")
            emit("")
        continue
    # recursive group: the types of the group
    tys = {clone_type(f): f for f in fs}
    tyshort = {t: t.split(".")[-1] for t in tys}

    def group_member(tystr: str, prefix: str = ""):
        s = canon_text(tystr).strip()
        if s.startswith("(") and s.endswith(")"):
            s = s[1:-1].strip()
        # A type inside the combined layout's namespace may be written relative to it.
        for n in (s, canon(prefix + s)) if prefix else (s,):
            for t in tys:
                if n == t or n.startswith(t + " "):
                    return t
        return None

    # nested carriers used in the group
    nests = {"vec": set()}
    cases = {}
    for f in fs:
        t = clone_type(f)
        tb = type_block(t)
        params, ctors = parse_type(tb)
        cs = []
        for cname, fields in ctors:
            pats, facts, optvars = [], [], []
            for k, (fname, fty) in enumerate(fields):
                v = f"a{k}"
                fty_n = canon_text(fty).strip()
                mt = group_member(fty_n, tb["prefix"])
                mv = re.match(r"^Aeneas\.Std\.NestedVec\s+(.*)$", fty_n)
                mo = re.match(r"^Option\s+(.*)$", fty_n)
                if mt:
                    pats.append(v)
                    facts.append(f"{thm_name(tys[mt])}{binders(tys[mt])[1]} {v}")
                elif mv and group_member(mv.group(1), tb["prefix"]):
                    mt = group_member(mv.group(1), tb["prefix"])
                    nests["vec"].add(mt)
                    pats.append(f"⟨n{k}, l{k}, hl{k}⟩")
                    fa = binders(tys[mt])[1]
                    facts.append(f"nvec_{tyshort[mt]}{fa} l{k} hl{k} (lenlist_{tyshort[mt]}{fa} l{k})")
                elif mo:
                    # Option fields split into none / some: the unfolded Option clone matches
                    # on the field; a group member's `some` branch also needs its theorem.
                    optvars.append((k, group_member(mo.group(1), tb["prefix"])))
                    pats.append(None)
                else:
                    pats.append(v)
            # expand option fields into none / some
            combos = [[]]
            for k, mt in optvars:
                combos = [c + [(k, False, mt)] for c in combos] + [c + [(k, True, mt)] for c in combos]
            for combo in combos:
                p = list(pats)
                fct = list(facts)
                for k, some, mt in combo:
                    if some:
                        p[k] = f"(some o{k})"
                        if mt:
                            fct.append(f"{thm_name(tys[mt])}{binders(tys[mt])[1]} o{k}")
                    else:
                        p[k] = "none"
                cs.append((cname, p, fct))
        cases[f] = (params, cs)
    # non-mutual helpers for the vec nests
    for mt in sorted(nests["vec"]):
        f = tys[mt]
        bs, args = binders(f)
        elem = self_type(f)
        inst = clone_type(f) + inst_suffix + "".join(f" {i}" for i, _ in fn_params(f)[1])
        emit(f"theorem nvec_{tyshort[mt]}{bs} {{n : Nat}} (l : Aeneas.Std.LenList ({elem}) n)")
        emit(f"    (hl : n ≤ Aeneas.Std.Usize.max)")
        emit(f"    (h : ∀ x ∈ l.toList, {clone_app(f)} x = .ok x) :")
        emit(f"    Aeneas.Std.alloc.vec.CloneVec.clone ({inst}) (Aeneas.Std.NestedVec.toVec ⟨n, l, hl⟩) =")
        emit(f"      .ok (Aeneas.Std.NestedVec.toVec ⟨n, l, hl⟩) :=")
        emit(f"  CloneId.vec _ _ (by simpa using h)")
        emit("")
    emit("mutual")
    for f in fs:
        bs, args = binders(f)
        ty = self_type(f)
        params, cs = cases[f]
        hyps = [f"h_{i}" for i, _ in fn_params(f)[1]]
        emit(f"theorem {thm_name(f)}{bs} : (x : {ty}) → {clone_app(f)} x = .ok x")
        for cname, p, fct in cs:
            pat = f".{cname}" + "".join(f" {q}" for q in p)
            simps = ", ".join(["lift", "Aeneas.Std.core.option.Option.Clone.clone",
                               "Aeneas.Std.core.alloc.boxed.CloneBox.clone"] + hyps + fct)
            emit(f"  | {pat} => by")
            emit(f"    rw [{f}.eq_def]")
            # `rw` closes nullary constructors by `rfl`
            emit(f"    all_goals simp [{simps}]")
            emit(f"    all_goals rfl")
    for mt in sorted(nests["vec"]):
        f = tys[mt]
        bs, args = binders(f)
        elem = self_type(f)
        emit(f"theorem lenlist_{tyshort[mt]}{bs} : {{n : Nat}} → (l : Aeneas.Std.LenList ({elem}) n) →")
        emit(f"    ∀ x ∈ l.toList, {clone_app(f)} x = .ok x")
        emit(f"  | _, .nil => by simp")
        emit(f"  | _, .cons y t => by")
        emit(f"    intro x hx")
        emit(f"    simp only [Aeneas.Std.LenList.toList_cons, List.mem_cons] at hx")
        emit(f"    rcases hx with rfl | hx")
        emit(f"    · exact {thm_name(f)}{args} x")
        emit(f"    · exact lenlist_{tyshort[mt]}{args} t x hx")
    emit("end")
    emit("")
    for f in fs:
        emit(f"attribute [simp] {thm_name(f)}")
    emit("")

emit(f"end {LEAN_NS}")
generated = "\n".join(out) + "\n"
summary = f"{len(seen)} clone functions in {len(groups)} groups from {len(files)} model files"
if check:
    if generated != module_text:
        sys.stdout.writelines(list(difflib.unified_diff(
            module_text.splitlines(keepends=True), generated.splitlines(keepends=True),
            fromfile=out_path, tofile="generated from the model", n=1))[:80])
        print(f"STALE: {out_path} differs from the theorems this model generates ({summary}); "
              f"regenerate with: python3 gen_clone_id.py {' '.join(cli)}")
        raise SystemExit(1)
    print(f"{out_path} matches the model: {summary}")
else:
    open(out_path, "w").write(generated)
    print(f"{summary} -> {out_path}")
