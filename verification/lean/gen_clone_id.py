"""Generate the clone-identity theorems of `ChelisBridge/Runtime/CloneId.lean`: for the derived
`Clone` impls a generated model reaches from given root clone functions.

usage: gen_clone_id.py <model.lean> <model namespace> <module.lean> <lean namespace> <root clone def>...

`<module.lean>` keeps everything up to and including its line `MARKER` (the hand-written
library lemmas); everything after it is replaced by the generated theorems and the closing
`end <lean namespace>`.

For every derived clone function `F` of a type `T` in the closure (in dependency order), emits
`theorem cid_<T> (insts…) (hyps…) : ∀ x : T, F insts… x = .ok x` (generic types take each
parameter's clone instance and the hypothesis that it is the identity). Non-recursive
functions: `cases x <;> simp [F, …]` with the clone lemmas of the library and of earlier
types as conditional simp lemmas. Recursive groups (`partial_fixpoint`, `mutual`): one
`mutual` block of structurally recursive theorems by constructor patterns (every `Option`
field split into `none` / `some`), with helper theorems for the `NestedVec` nests of the
group's types.
"""
import re
import sys

MARKER = "-- Generated by gen_clone_id.py below this line; do not edit."

src, NS, out_path, LEAN_NS, *roots = sys.argv[1:]
text = open(src).read()
lines = text.split("\n")

FOREIGN = ("chelis_types", "chelis_unord", "chelis_deep", "chelis_effects", "core", "alloc", "half",
           "std", "serde")


def norm(name: str) -> str:
    """A model name as the bridge spells it (both layouts, after `open <root crate>`)."""
    name = name.removeprefix("_root_.")
    if name.startswith("Aeneas.Std."):
        return name
    if name.startswith(NS + "."):
        rest = name[len(NS) + 1:]
        if rest.split(".")[0] in FOREIGN:
            return rest
        return name
    return name


# ---------------------------------------------------------------------------------------------
# Top-level blocks: (kind, name, start line, end line, in_mutual id)
blocks = []
mutual_id = None
mcount = 0
i = 0
decl_re = re.compile(r"^(?:noncomputable )?(inductive|structure|def|theorem|abbrev)\s+(\S+)")
while i < len(lines):
    line = lines[i]
    if line.strip() == "mutual":
        mcount += 1
        mutual_id = mcount
        i += 1
        continue
    if line.strip() == "end" and mutual_id is not None:
        mutual_id = None
        i += 1
        continue
    m = decl_re.match(line)
    if m:
        j = i + 1
        while j < len(lines) and not decl_re.match(lines[j]) and not lines[j].startswith("/--") \
                and lines[j].strip() not in ("mutual", "end") and not lines[j].startswith("@["):
            j += 1
        blocks.append({"kind": m.group(1), "name": m.group(2), "start": i, "end": j, "mutual": mutual_id})
        i = j
        continue
    i += 1

by_name = {}
for b in blocks:
    by_name.setdefault(b["name"], b)


def full(name: str) -> str:
    """The absolute model name of a declared name."""
    return name if name.startswith("_root_.") else f"_root_.{NS}.{name}"


def body(b) -> str:
    return "\n".join(lines[b["start"]:b["end"]])


def split_arrows(s: str):
    parts, depth, cur = [], 0, ""
    k = 0
    while k < len(s):
        c = s[k]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if depth == 0 and s.startswith("→", k):
            parts.append(cur.strip())
            cur = ""
            k += 1
            continue
        cur += c
        k += 1
    parts.append(cur.strip())
    return parts


def parse_type(b):
    """(params, ctors) with ctors = [(ctor name, [field types])]; structures: one ctor `mk`
    with named fields [(field, type)]."""
    head = lines[b["start"]]
    params = re.findall(r"\((\w+) : Type\)", head)
    ctors = []
    if b["kind"] == "inductive":
        cur = None
        for line in lines[b["start"] + 1:b["end"]]:
            if line.startswith("| "):
                if cur:
                    ctors.append(cur)
                m = re.match(r"\| (\w+) :(.*)", line)
                cur = [m.group(1), m.group(2)]
            elif cur and line.strip():
                cur[1] += " " + line.strip()
        if cur:
            ctors.append(cur)
        result = []
        for name, ty in ctors:
            parts = split_arrows(ty.strip())
            result.append((name, [(None, p) for p in parts[:-1]]))
        return params, result
    fields = []
    for line in lines[b["start"] + 1:b["end"]]:
        m = re.match(r"^  (\w+) :(.*)", line)
        if m:
            fields.append([m.group(1), m.group(2).strip()])
        elif fields and line.startswith("    "):
            fields[-1][1] += " " + line.strip()
    return params, [("mk", [(f, t) for f, t in fields])]


clone_suffix = ".Insts.CoreCloneClone.clone"
inst_suffix = ".Insts.CoreCloneClone"


def clone_type(fname: str) -> str:
    return fname[: -len(clone_suffix)]


ident = re.compile(r"[A-Za-z_][A-Za-z0-9_'.]*")


def rel(name: str) -> str:
    n = name.removeprefix("_root_.")
    return n[len(NS) + 1:] if n.startswith(NS + ".") else n


# closure of clone functions
seen, order, stack = set(), [], [r for r in roots]
deps = {}
while stack:
    f = stack.pop()
    if f in seen:
        continue
    if f not in by_name:
        raise SystemExit(f"no definition {f}")
    seen.add(f)
    refs = set()
    for tok in ident.findall(body(by_name[f])):
        t = rel(tok)
        if t == f:
            continue
        if t.endswith(clone_suffix) and t in by_name:
            refs.add(t)
        elif t.endswith(inst_suffix) and t + ".clone" in by_name:
            refs.add(t + ".clone")
    deps[f] = refs
    stack.extend(sorted(refs))

# groups: a mutual block, or a single function
group_of = {}
for f in seen:
    b = by_name[f]
    group_of[f] = ("m", b["mutual"]) if b["mutual"] else ("s", f)
groups = {}
for f in seen:
    groups.setdefault(group_of[f], []).append(f)

# topological order of groups
gdeps = {g: {group_of[d] for f in fs for d in deps[f]} - {g} for g, fs in groups.items()}
ordered, done = [], set()


def visit(g, path=()):
    if g in done:
        return
    if g in path:
        raise SystemExit(f"cycle between groups {path}")
    for d in sorted(gdeps[g], key=str):
        visit(d, path + (g,))
    done.add(g)
    ordered.append(g)


for g in sorted(groups, key=str):
    visit(g)


def thm_name(f: str) -> str:
    return "cid_" + clone_type(f).replace(".", "_")


def fn_params(f: str):
    """Implicit type params and (inst name, type param) of a clone def."""
    head = body(by_name[f]).split(":=")[0]
    tparams = re.findall(r"\{(\w+) : Type\}", head)
    insts = re.findall(r"\((\w+) :\s*_root_\.Aeneas\.Std\.core\.clone\.Clone (\w+)\)", head)
    return tparams, insts


def self_type(f: str) -> str:
    head = body(by_name[f])
    m = re.search(r"\(self :\s*(.*?)\)\s*:\s*\n", head, re.S)
    if not m:
        m = re.search(r"\(self :\s*([^)]*(?:\([^)]*\))?[^)]*)\)", head, re.S)
    return " ".join(m.group(1).split())


def binders(f: str) -> tuple[str, str]:
    tparams, insts = fn_params(f)
    bs = "".join(f" {{{t} : Type}}" for t in tparams)
    args = ""
    for inst, t in insts:
        bs += (f" ({inst} : Aeneas.Std.core.clone.Clone {t})"
               f" (h_{inst} : ∀ y, {inst}.clone y = .ok y)")
        args += f" {inst} h_{inst}"
    return bs, args


def clone_app(f: str) -> str:
    _, insts = fn_params(f)
    return f"{norm(full(f))}" + "".join(f" {i}" for i, _ in insts)


module_lines = open(out_path).read().split("\n")
if MARKER not in module_lines:
    raise SystemExit(f"{out_path}: no line {MARKER!r}")
out = module_lines[: module_lines.index(MARKER) + 1] + [""]
emit = out.append


def type_block(tyname: str):
    b = by_name.get(tyname)
    if b is None:
        raise SystemExit(f"no type {tyname}")
    return b


for g in ordered:
    fs = sorted(groups[g])
    recursive = any("partial_fixpoint" in body(by_name[f]) for f in fs)
    if not recursive:
        for f in fs:
            bs, _ = binders(f)
            ty = norm(self_type(f))
            hyps = ", ".join(f"h_{i}" for i, _ in fn_params(f)[1])
            emit(f"@[simp] theorem {thm_name(f)}{bs} (x : {ty}) :")
            emit(f"    {clone_app(f)} x = .ok x := by")
            emit(f"  cases x <;> simp [{norm(full(f))}{', ' + hyps if hyps else ''}] <;> rfl")
            emit("")
        continue
    # recursive group: the types of the group
    tys = {clone_type(f): f for f in fs}
    tyshort = {t: t.split(".")[-1] for t in tys}

    def group_member(tystr: str):
        s = norm(tystr).strip()
        if s.startswith("(") and s.endswith(")"):
            s = s[1:-1].strip()
        s = s.removeprefix("_root_.")
        for t in tys:
            for n in (t, f"{NS}.{t}", norm(full(t))):
                if s == n or s.startswith(n + " "):
                    return t
        return None

    helpers = []
    # nested carriers used in the group
    nests = {"vec": set(), "opt": set()}
    cases = {}
    for f in fs:
        t = clone_type(f)
        params, ctors = parse_type(type_block(t))
        cs = []
        for cname, fields in ctors:
            pats, facts, optvars = [], [], []
            for k, (fname, fty) in enumerate(fields):
                v = f"a{k}"
                fty_n = norm(fty).strip()
                mt = group_member(fty_n)
                fty_n = fty_n.removeprefix("_root_.")
                mv = re.match(r"^Aeneas\.Std\.NestedVec\s+(.*)$", fty_n)
                mo = re.match(r"^Option\s+(.*)$", fty_n)
                if mt:
                    pats.append(v)
                    facts.append(f"{thm_name(tys[mt])}{binders(tys[mt])[1]} {v}")
                elif mv and group_member(mv.group(1)):
                    mt = group_member(mv.group(1))
                    nests["vec"].add(mt)
                    pats.append(f"⟨n{k}, l{k}, hl{k}⟩")
                    fa = binders(tys[mt])[1]
                    facts.append(f"nvec_{tyshort[mt]}{fa} l{k} hl{k} (lenlist_{tyshort[mt]}{fa} l{k})")
                elif mo:
                    # Option fields split into none / some: the unfolded Option clone matches
                    # on the field; a group member's `some` branch also needs its theorem.
                    optvars.append((k, group_member(mo.group(1))))
                    pats.append(None)
                else:
                    pats.append(v)
            # expand option fields into none / some
            combos = [[]]
            for k, mt in optvars:
                combos = [c + [(k, False, mt)] for c in combos] + [c + [(k, True, mt)] for c in combos]
            for combo in combos:
                p = list(pats)
                fct = list(facts)
                for k, some, mt in combo:
                    if some:
                        p[k] = f"(some o{k})"
                        if mt:
                            fct.append(f"{thm_name(tys[mt])}{binders(tys[mt])[1]} o{k}")
                    else:
                        p[k] = "none"
                cs.append((cname, p, fct))
        cases[f] = (params, cs)
    # non-mutual helpers for the vec nests
    for mt in sorted(nests["vec"]):
        f = tys[mt]
        bs, args = binders(f)
        elem = norm(self_type(f))
        inst = norm(full(clone_type(f) + inst_suffix)) + "".join(f" {i}" for i, _ in fn_params(f)[1])
        emit(f"theorem nvec_{tyshort[mt]}{bs} {{n : Nat}} (l : Aeneas.Std.LenList ({elem}) n)")
        emit(f"    (hl : n ≤ Aeneas.Std.Usize.max)")
        emit(f"    (h : ∀ x ∈ l.toList, {clone_app(f)} x = .ok x) :")
        emit(f"    Aeneas.Std.alloc.vec.CloneVec.clone ({inst}) (Aeneas.Std.NestedVec.toVec ⟨n, l, hl⟩) =")
        emit(f"      .ok (Aeneas.Std.NestedVec.toVec ⟨n, l, hl⟩) :=")
        emit(f"  CloneId.vec _ _ (by simpa using h)")
        emit("")
    emit("mutual")
    for f in fs:
        bs, args = binders(f)
        ty = norm(self_type(f))
        params, cs = cases[f]
        hyps = [f"h_{i}" for i, _ in fn_params(f)[1]]
        emit(f"theorem {thm_name(f)}{bs} : (x : {ty}) → {clone_app(f)} x = .ok x")
        for cname, p, fct in cs:
            pat = f".{cname}" + "".join(f" {q}" for q in p)
            simps = ", ".join(["lift", "Aeneas.Std.core.option.Option.Clone.clone",
                               "Aeneas.Std.core.alloc.boxed.CloneBox.clone"] + hyps + fct)
            emit(f"  | {pat} => by")
            emit(f"    rw [{norm(full(f))}.eq_def]")
            # `rw` closes nullary constructors by `rfl`
            emit(f"    all_goals simp [{simps}]")
            emit(f"    all_goals rfl")
    for mt in sorted(nests["vec"]):
        f = tys[mt]
        bs, args = binders(f)
        elem = norm(self_type(f))
        emit(f"theorem lenlist_{tyshort[mt]}{bs} : {{n : Nat}} → (l : Aeneas.Std.LenList ({elem}) n) →")
        emit(f"    ∀ x ∈ l.toList, {clone_app(f)} x = .ok x")
        emit(f"  | _, .nil => by simp")
        emit(f"  | _, .cons y t => by")
        emit(f"    intro x hx")
        emit(f"    simp only [Aeneas.Std.LenList.toList_cons, List.mem_cons] at hx")
        emit(f"    rcases hx with rfl | hx")
        emit(f"    · exact {thm_name(f)}{args} x")
        emit(f"    · exact lenlist_{tyshort[mt]}{args} t x hx")
    emit("end")
    emit("")
    for f in fs:
        emit(f"attribute [simp] {thm_name(f)}")
    emit("")

emit(f"end {LEAN_NS}")
open(out_path, "w").write("\n".join(out) + "\n")
print(f"{len(seen)} clone functions in {len(groups)} groups -> {out_path}")
for g in ordered:
    print(g, sorted(groups[g]))
