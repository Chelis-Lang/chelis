/// Collect the bindings that make `pattern` equal to `concrete`.
///
/// This is one-directional matching, not full unification: `pattern` carries
/// the generic's variables and `concrete` is the call site's resolved type.
/// A position where `concrete` is itself unresolved contributes nothing, so a
/// partially-known call site still binds what it does know. The first binding
/// for a variable wins, which is why callers unify parameters (specific)
/// before the return type (often only `Unknown`).
pub(crate) fn collect_type_var_bindings(
    pattern: &HostTypeTerm,
    concrete: &HostTypeTerm,
    out: &mut HashMap<String, HostTypeTerm>,
) {
    match (pattern, concrete) {
        (HostTypeTerm::TypeVariable(name), value) => {
            if !value.is_unresolved() {
                out.entry(name.clone()).or_insert_with(|| value.clone());
            }
        }
        (HostTypeTerm::Fn(pattern_params, pattern_ret), HostTypeTerm::Fn(params, ret)) => {
            for (pattern_param, param) in pattern_params.iter().zip(params) {
                collect_type_var_bindings(pattern_param, param, out);
            }
            collect_type_var_bindings(pattern_ret, ret, out);
        }
        (HostTypeTerm::Adt(pattern_name, pattern_args), HostTypeTerm::Adt(name, args))
            if pattern_name == name =>
        {
            for (pattern_arg, arg) in pattern_args.iter().zip(args) {
                collect_type_var_bindings(pattern_arg, arg, out);
            }
        }
        (HostTypeTerm::Tuple(pattern_items), HostTypeTerm::Tuple(items)) => {
            for (pattern_item, item) in pattern_items.iter().zip(items) {
                collect_type_var_bindings(pattern_item, item, out);
            }
        }
        (HostTypeTerm::List(pattern_inner), HostTypeTerm::List(inner))
        | (HostTypeTerm::Option(pattern_inner), HostTypeTerm::Option(inner)) => {
            collect_type_var_bindings(pattern_inner, inner, out);
        }
        (HostTypeTerm::Dict(pattern_key, pattern_value), HostTypeTerm::Dict(key, value)) => {
            collect_type_var_bindings(pattern_key, key, out);
            collect_type_var_bindings(pattern_value, value, out);
        }
        // A signature-quantified precision or rank variable binds from the
        // call's concrete tensor. Those forms have their own specialization
        // paths and normally never reach here; handling them costs nothing
        // and keeps a mixed signature from silently binding only half.
        (HostTypeTerm::PolymorphicTensor(pattern_tensor), HostTypeTerm::Tensor(tensor)) => {
            if let HostPrecisionTerm::Variable(name) = &pattern_tensor.precision {
                out.entry(name.clone()).or_insert_with(|| {
                    HostTypeTerm::Scalar(HostPrecisionTerm::Concrete(tensor.precision))
                });
            }
        }
        _ => {}
    }
}

/// Every type-variable name still free in `ty`.
pub(crate) fn collect_free_type_vars(ty: &HostTypeTerm, out: &mut HashSet<String>) {
    match ty {
        HostTypeTerm::TypeVariable(name)
        | HostTypeTerm::Scalar(HostPrecisionTerm::Variable(name)) => {
            out.insert(name.clone());
        }
        HostTypeTerm::Fn(params, ret) => {
            for param in params {
                collect_free_type_vars(param, out);
            }
            collect_free_type_vars(ret, out);
        }
        HostTypeTerm::Adt(_, args) | HostTypeTerm::Tuple(args) => {
            for arg in args {
                collect_free_type_vars(arg, out);
            }
        }
        HostTypeTerm::List(inner) | HostTypeTerm::Option(inner) => {
            collect_free_type_vars(inner, out);
        }
        HostTypeTerm::Dict(key, value) => {
            collect_free_type_vars(key, out);
            collect_free_type_vars(value, out);
        }
        HostTypeTerm::PolymorphicTensor(tensor) => {
            if let HostPrecisionTerm::Variable(name) = &tensor.precision {
                out.insert(name.clone());
            }
            if let HostShapeTerm::Polymorphic(slots) = &tensor.shape {
                for slot in slots {
                    if let HostShapeSlot::RankVariable(name) = slot {
                        out.insert(name.clone());
                    }
                }
            }
        }
        _ => {}
    }
}

/// Replace every bound type variable in `ty`.
pub(crate) fn apply_type_var_bindings(
    ty: &HostTypeTerm,
    env: &HashMap<String, HostTypeTerm>,
) -> HostTypeTerm {
    match ty {
        HostTypeTerm::TypeVariable(name) => env.get(name).cloned().unwrap_or_else(|| ty.clone()),
        HostTypeTerm::Fn(params, ret) => HostTypeTerm::Fn(
            params
                .iter()
                .map(|param| apply_type_var_bindings(param, env))
                .collect(),
            Box::new(apply_type_var_bindings(ret, env)),
        ),
        HostTypeTerm::Adt(name, args) => HostTypeTerm::Adt(
            name.clone(),
            args.iter()
                .map(|arg| apply_type_var_bindings(arg, env))
                .collect(),
        ),
        HostTypeTerm::Tuple(items) => HostTypeTerm::Tuple(
            items
                .iter()
                .map(|item| apply_type_var_bindings(item, env))
                .collect(),
        ),
        HostTypeTerm::List(inner) => {
            HostTypeTerm::List(Box::new(apply_type_var_bindings(inner, env)))
        }
        HostTypeTerm::Option(inner) => {
            HostTypeTerm::Option(Box::new(apply_type_var_bindings(inner, env)))
        }
        HostTypeTerm::Dict(key, value) => HostTypeTerm::Dict(
            Box::new(apply_type_var_bindings(key, env)),
            Box::new(apply_type_var_bindings(value, env)),
        ),
        HostTypeTerm::Scalar(HostPrecisionTerm::Variable(name)) => match env.get(name) {
            Some(HostTypeTerm::Scalar(HostPrecisionTerm::Concrete(prim))) => {
                HostTypeTerm::Scalar(HostPrecisionTerm::Concrete(*prim))
            }
            _ => ty.clone(),
        },
        HostTypeTerm::PolymorphicTensor(tensor) => {
            let precision = match &tensor.precision {
                HostPrecisionTerm::Variable(name) => match env.get(name) {
                    Some(HostTypeTerm::Scalar(HostPrecisionTerm::Concrete(prim))) => {
                        HostPrecisionTerm::Concrete(*prim)
                    }
                    _ => tensor.precision.clone(),
                },
                concrete => concrete.clone(),
            };
            match (&precision, &tensor.shape) {
                (HostPrecisionTerm::Concrete(prim), HostShapeTerm::Concrete(dims)) => {
                    HostTypeTerm::Tensor(TensorType {
                        dims: dims.clone(),
                        precision: *prim,
                    })
                }
                _ => HostTypeTerm::PolymorphicTensor(HostTensorTypeTerm {
                    precision,
                    shape: tensor.shape.clone(),
                }),
            }
        }
        other => other.clone(),
    }
}

