//! Bounded memoized monomorphization for recursive generic host calls
//! (chelis#1158, successor to chelis#941).
//!
//! # Why outlining rather than inlining
//!
//! A type-polymorphic top-level function has no standalone C ABI, so
//! `lower_host_program` deliberately does not emit one: a `Box[a]` cannot
//! cross a concrete host boundary before a call site binds `a`. Until this
//! module existed, the only way to reach such a body was call-site inlining,
//! which cannot terminate when the callee participates in a call cycle — so
//! every recursive generic call was rejected under `[05-UNS-1]`.
//!
//! The fix is to stop inlining recursive generics and start *outlining* them.
//! A call site whose callee is type-polymorphic resolves the call's fully
//! concrete signature, interns `(callee, canonical signature) -> mangled
//! symbol`, enqueues the pair the first time it is seen, and emits an
//! ordinary C call. After the main lowering pass drains the worklist, each
//! pending pair is lowered once as a standalone `HostFunction` with the
//! generic's type variables bound to the interned concrete terms. Recursive
//! calls inside a draining body re-enter the interner, hit the memo, and
//! become ordinary calls too.
//!
//! Termination is by memoization, so **mutual recursion needs no SCC
//! analysis**: each distinct pair is enqueued exactly once and a cycle
//! resolves to an already-interned symbol.
//!
//! # What still cannot be monomorphized
//!
//! Polymorphic recursion — a cycle that keeps minting *new* instantiations,
//! as in `f[a]` calling `f[(a, a)]` — has no finite family of monomorphic
//! symbols, so it stays on the (now narrowed) `[05-UNS-1]` boundary. Two
//! caps keep that fail-loud rather than divergent: [`MONO_SPECIALIZATION_CAP`]
//! bounds how many distinct specializations one callee may mint, and
//! [`MONO_SIGNATURE_NODE_CAP`] bounds one signature's size. The size cap is
//! not redundant: the `f[(a, a)]` shape doubles the type at every level, so
//! the count cap alone would be reached only after building a signature with
//! 2^64 nodes.
//!
//! # V1 scope
//!
//! Only **fully concrete** signatures are interned. A call site that still
//! carries a free type, precision, or rank variable after unification falls
//! through to the pre-existing inline/rejection paths untouched, so this
//! module never interacts with the precision- and rank-polymorphism
//! machinery.

use std::cell::RefCell;
use std::collections::{HashMap, HashSet, VecDeque};

use chelis_deep::DeepTag;
use chelis_deep::ast::{Atom, Expr, List, MetaMap};

use crate::dag::{DimInfo, TensorType};
