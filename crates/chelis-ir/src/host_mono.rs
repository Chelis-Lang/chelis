/// A deterministic, injective-enough rendering of one signature. Used both as
/// the memo key and as the hash input for the emitted symbol, so it must not
/// depend on hash-map iteration order or on pointer identity.
pub(crate) fn canonical_signature_key(params: &[HostTypeTerm], ret: &HostTypeTerm) -> String {
    let mut out = String::from("(");
    for (index, param) in params.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        render_host_type(param, &mut out);
    }
    out.push_str(")->");
    render_host_type(ret, &mut out);
    out
}

/// The canonical rendering of one type term, for diagnostics.
pub(crate) fn render_host_type_term(ty: &HostTypeTerm) -> String {
    let mut out = String::new();
    render_host_type(ty, &mut out);
    out
}

fn render_host_type(ty: &HostTypeTerm, out: &mut String) {
    match ty {
        HostTypeTerm::Scalar(HostPrecisionTerm::Concrete(prim)) => out.push_str(prim.name()),
        HostTypeTerm::Scalar(HostPrecisionTerm::Variable(name)) => {
            out.push_str("%prec:");
            out.push_str(name);
        }
        HostTypeTerm::Fn(params, ret) => {
            out.push_str("fn(");
            for (index, param) in params.iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                render_host_type(param, out);
            }
            out.push_str(")->");
            render_host_type(ret, out);
        }
        HostTypeTerm::Adt(name, args) => {
            out.push_str(name);
            out.push('[');
            for (index, arg) in args.iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                render_host_type(arg, out);
            }
            out.push(']');
        }
        HostTypeTerm::List(inner) => {
            out.push_str("List[");
            render_host_type(inner, out);
            out.push(']');
        }
        HostTypeTerm::Option(inner) => {
            out.push_str("Option[");
            render_host_type(inner, out);
            out.push(']');
        }
        HostTypeTerm::Dict(key, value) => {
            out.push_str("Dict[");
            render_host_type(key, out);
            out.push(',');
            render_host_type(value, out);
            out.push(']');
        }
        HostTypeTerm::Tuple(items) => {
            out.push('(');
            for (index, item) in items.iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                render_host_type(item, out);
            }
            out.push(')');
        }
        HostTypeTerm::Tensor(tensor) => {
            out.push_str("tensor[");
            for dim in &tensor.dims {
                render_dim(dim, out);
                out.push(',');
            }
            out.push_str(tensor.precision.name());
            out.push(']');
        }
        HostTypeTerm::PolymorphicTensor(tensor) => {
            out.push_str("tensor?[");
            match &tensor.shape {
                HostShapeTerm::Concrete(dims) => {
                    for dim in dims {
                        render_dim(dim, out);
                        out.push(',');
                    }
                }
                HostShapeTerm::Polymorphic(slots) => {
                    for slot in slots {
                        match slot {
                            HostShapeSlot::Dim(dim) => render_dim(dim, out),
                            HostShapeSlot::RankVariable(name) => {
                                out.push_str("%rank:");
                                out.push_str(name);
                            }
                        }
                        out.push(',');
                    }
                }
            }
            match &tensor.precision {
                HostPrecisionTerm::Concrete(prim) => out.push_str(prim.name()),
                HostPrecisionTerm::Variable(name) => {
                    out.push_str("%prec:");
                    out.push_str(name);
                }
            }
            out.push(']');
        }
        HostTypeTerm::MappedFile => out.push_str("MappedFile"),
        HostTypeTerm::Unit => out.push_str("unit"),
        HostTypeTerm::TypeVariable(name) => {
            out.push_str("%var:");
            out.push_str(name);
        }
        HostTypeTerm::InferenceVariable(var) => {
            out.push_str("%inf:");
            out.push_str(&var.0.to_string());
        }
        HostTypeTerm::Never => out.push_str("never"),
    }
}

fn render_dim(dim: &DimInfo, out: &mut String) {
    match dim {
        DimInfo::Lit(value) => out.push_str(&value.to_string()),
        DimInfo::Named(name, None) => out.push_str(name),
        DimInfo::Named(name, Some(value)) => {
            out.push_str(name);
            out.push('=');
            out.push_str(&value.to_string());
        }
    }
}

/// The infix that marks an emitted symbol as a monomorphized specialization
/// rather than an authored def. A Chelis source identifier cannot contain it
/// in this position, because `mono_symbol` is the only producer.
const MONO_SYMBOL_INFIX: &str = "__mono_";

/// Whether an emitted host function name is a chelis#1158 specialization.
///
/// The C backend asks so it can keep these out of the program's published
/// `.h`: the name is a hash of an interned signature, it moves whenever the
/// instantiation set does, and it is compiler-owned. Kept here rather than
/// re-derived in the backend so one module owns the convention.
pub fn is_monomorphized_specialization(name: &str) -> bool {
    name.contains(MONO_SYMBOL_INFIX)
}

/// The emitted C symbol for one specialization.
///
/// The hash is FNV-1a rather than `DefaultHasher`: `std`'s default hasher is
/// explicitly not stable across releases or processes, and an unstable symbol
/// name would make the emitted `.c` non-reproducible (chelis#1002). Non-C
/// identifier bytes in the callee (a dotted module path, for example) are
/// folded to `_` so the result is always a legal C identifier.
pub(crate) fn mono_symbol(callee: &str, signature_key: &str) -> String {
    let mut sanitized = String::with_capacity(callee.len());
    for byte in callee.chars() {
        if byte.is_ascii_alphanumeric() || byte == '_' {
            sanitized.push(byte);
        } else {
            sanitized.push('_');
        }
    }
    if sanitized.starts_with(|c: char| c.is_ascii_digit()) {
        sanitized.insert(0, '_');
    }
    format!(
        "{sanitized}{MONO_SYMBOL_INFIX}{:016x}",
        fnv1a64(signature_key.as_bytes())
    )
}

fn fnv1a64(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

/// Structural node count of a type term. Bounds the worklist's allocation:
/// see [`MONO_SIGNATURE_NODE_CAP`].
pub(crate) fn host_type_node_count(ty: &HostTypeTerm) -> usize {
    match ty {
        HostTypeTerm::Fn(params, ret) => {
            1 + params.iter().map(host_type_node_count).sum::<usize>() + host_type_node_count(ret)
        }
        HostTypeTerm::Adt(_, args) | HostTypeTerm::Tuple(args) => {
            1 + args.iter().map(host_type_node_count).sum::<usize>()
        }
        HostTypeTerm::List(inner) | HostTypeTerm::Option(inner) => 1 + host_type_node_count(inner),
        HostTypeTerm::Dict(key, value) => {
            1 + host_type_node_count(key) + host_type_node_count(value)
        }
        _ => 1,
    }
}

