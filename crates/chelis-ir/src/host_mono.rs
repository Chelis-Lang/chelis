/// Maximum number of distinct monomorphic specializations one generic callee
/// may mint in a single program. A legitimate program instantiates a generic
/// at a handful of types; exceeding this bound means the instantiation family
/// is being generated by the recursion itself.
pub(crate) const MONO_SPECIALIZATION_CAP: usize = 64;

/// Maximum number of type-term nodes in one interned signature. Polymorphic
/// recursion that grows the type multiplicatively (`f[a]` calling `f[(a, a)]`)
/// reaches this long before [`MONO_SPECIALIZATION_CAP`], and reaching it is
/// the only thing that keeps the worklist from allocating a signature larger
/// than memory.
pub(crate) const MONO_SIGNATURE_NODE_CAP: usize = 512;

/// One `(callee, concrete signature)` pair awaiting outlined emission.
#[derive(Debug, Clone)]
pub(crate) struct PendingSpecialization {
    /// The generic top-level def this specializes.
    pub(crate) callee: String,
    /// The emitted C symbol for this specialization.
    pub(crate) symbol: String,
    /// Fully concrete parameter types, positionally matching the def's params.
    pub(crate) params: Vec<HostTypeTerm>,
    /// Fully concrete return type.
    pub(crate) ret: HostTypeTerm,
    /// Instantiation chain that reached this specialization, oldest first.
    /// Rendered into the cap diagnostic so polymorphic recursion is
    /// debuggable rather than merely rejected.
    pub(crate) chain: Vec<String>,
}

/// The type-variable bindings in force while one specialization's body is
/// being lowered.
#[derive(Debug, Clone)]
struct MonoFrame {
    callee: String,
    bindings: HashMap<String, HostTypeTerm>,
    chain: Vec<String>,
}

thread_local! {
    /// `(callee, canonical signature)` -> emitted symbol. The memo is what
    /// makes the worklist terminate.
    static MONO_INTERN: RefCell<HashMap<(String, String), String>> =
        RefCell::new(HashMap::new());
    /// Pending specializations in first-seen order. FIFO, not a hash-map
    /// iteration, so emission order — and therefore the emitted `.c` — is
    /// deterministic (chelis#1002).
    static MONO_WORKLIST: RefCell<VecDeque<PendingSpecialization>> =
        const { RefCell::new(VecDeque::new()) };
    /// How many distinct specializations each callee has minted.
    static MONO_SPECIALIZATION_COUNTS: RefCell<HashMap<String, usize>> =
        RefCell::new(HashMap::new());
    /// Emitted symbol -> the canonical signature it was minted for. The
    /// reverse of `MONO_INTERN`, kept so a hash collision is caught rather
    /// than emitted: two signatures sharing a symbol would collapse into one
    /// C definition, and the emitter's duplicate-symbol check cannot see it
    /// (it compares distinct `HostFunction` names, which would be equal).
    static MONO_SYMBOL_ORIGINS: RefCell<HashMap<String, String>> =
        RefCell::new(HashMap::new());
    /// The stack of specializations currently being lowered.
    static MONO_FRAMES: RefCell<Vec<MonoFrame>> = const { RefCell::new(Vec::new()) };
}

/// Makes a speculative lowering side-effect-free on the interner.
///
/// Several lowering decisions are taken by *probing*: `top_level_fn_helper_
/// summary_rejects` fully lowers a callee body only to ask whether its tensor
/// helper would register a summary rejection, then throws the result away. The
/// lowering is discarded; the interning it performed was not. Three
/// consequences, all real:
///
/// 1. **Nondeterministic emitted C (chelis#1002).** The probe set is iterated
///    from a `HashSet`, so probe order varies per run. Whichever probe ran
///    first fixed that specialization's position in the FIFO worklist, and the
///    drain preserves worklist order into emission order. Measured: 25 builds
///    of one file produced two distinct `.c` hashes, differing only by two
///    `count__mono_*` definitions swapping places.
/// 2. **Cap budget consumed by discarded work.** `intern_specialization`
///    increments the per-callee count at intern time, so a probe could push a
///    program over [`MONO_SPECIALIZATION_CAP`] without any surviving call site.
/// 3. **Unconditional emission of probe-only specializations.** The drain
///    lowers every enqueued pair and propagates failure with `?`, so a
///    specialization that only ever existed inside a discarded probe can abort
///    the whole build.
///
/// Restoring the snapshot on scope exit removes all three at the root: after a
/// probe the interner is byte-for-byte what it was before, and every surviving
/// specialization was interned by the real lowering pass, in that pass's
/// deterministic traversal order.
pub(crate) struct MonoProbeGuard {
    intern: HashMap<(String, String), String>,
    worklist: VecDeque<PendingSpecialization>,
    counts: HashMap<String, usize>,
    symbol_origins: HashMap<String, String>,
    frames: Vec<MonoFrame>,
}

impl MonoProbeGuard {
    pub(crate) fn begin() -> Self {
        Self {
            intern: MONO_INTERN.with(|state| state.borrow().clone()),
            worklist: MONO_WORKLIST.with(|state| state.borrow().clone()),
            counts: MONO_SPECIALIZATION_COUNTS.with(|state| state.borrow().clone()),
            symbol_origins: MONO_SYMBOL_ORIGINS.with(|state| state.borrow().clone()),
            frames: MONO_FRAMES.with(|state| state.borrow().clone()),
        }
    }
}

impl Drop for MonoProbeGuard {
    fn drop(&mut self) {
        // Restore rather than clear: a probe can run while a specialization
        // body is being drained, and that outer frame must survive.
        MONO_INTERN.with(|state| *state.borrow_mut() = std::mem::take(&mut self.intern));
        MONO_WORKLIST.with(|state| *state.borrow_mut() = std::mem::take(&mut self.worklist));
        MONO_SPECIALIZATION_COUNTS
            .with(|state| *state.borrow_mut() = std::mem::take(&mut self.counts));
        MONO_SYMBOL_ORIGINS
            .with(|state| *state.borrow_mut() = std::mem::take(&mut self.symbol_origins));
        MONO_FRAMES.with(|state| *state.borrow_mut() = std::mem::take(&mut self.frames));
    }
}

/// Clear every interner cache. Called from the host-lowering cache guard so
/// one process may lower many programs without leaking symbols between them.
pub(crate) fn reset_mono_state() {
    MONO_INTERN.with(|intern| intern.borrow_mut().clear());
    MONO_WORKLIST.with(|worklist| worklist.borrow_mut().clear());
    MONO_SPECIALIZATION_COUNTS.with(|counts| counts.borrow_mut().clear());
    MONO_SYMBOL_ORIGINS.with(|origins| origins.borrow_mut().clear());
    MONO_FRAMES.with(|frames| frames.borrow_mut().clear());
}

/// Why a call site could not be monomorphized. Both variants keep the
/// `[05-UNS-1]` brand; they differ in what the author can do about it.
#[derive(Debug, Clone)]
pub(crate) enum MonoRejection {
    /// The call's type arguments did not resolve to a concrete signature, so
    /// there is nothing to intern. This is the residual chelis#730 shape.
    NotConcrete { detail: String },
    /// The instantiation family is unbounded: the recursion mints a new type
    /// at every level. No finite set of monomorphic symbols exists.
    UnboundedInstantiation { chain: Vec<String>, reason: String },
    /// Two distinct signatures hashed to one emitted symbol. Astronomically
    /// unlikely at 64 bits, and silently wrong if it ever happened, so it is
    /// a rejection rather than an assumption.
    SymbolCollision {
        symbol: String,
        signature: String,
        existing: String,
    },
}

impl MonoRejection {
    pub(crate) fn describe(&self, callee: &str) -> String {
        match self {
            Self::NotConcrete { detail } => format!(
                "generic host call `{callee}` has no monomorphic symbol: {detail} \
                 (chelis#1158; [05-UNS-1])"
            ),
            Self::UnboundedInstantiation { chain, reason } => format!(
                "generic host call `{callee}` requires unbounded monomorphization \
                 ({reason}); this is polymorphic recursion: the instantiation \
                 chain {} mints a new type at every level, so no finite set of \
                 monomorphic symbols exists (chelis#1158; [05-UNS-1])",
                render_chain(chain)
            ),
            Self::SymbolCollision {
                symbol,
                signature,
                existing,
            } => format!(
                "generic host call `{callee}` hashed signature `{signature}` onto \
                 symbol `{symbol}`, which signature `{existing}` already holds; \
                 emitting both would collapse two specializations into one C \
                 definition (chelis#1158; [05-UNS-1])"
            ),
        }
    }
}

fn render_chain(chain: &[String]) -> String {
    const SHOWN: usize = 4;
    let mut rendered = chain
        .iter()
        .take(SHOWN)
        .cloned()
        .collect::<Vec<_>>()
        .join(" -> ");
    if chain.len() > SHOWN {
        rendered.push_str(" -> ...");
    }
    if rendered.is_empty() {
        "(entry)".to_string()
    } else {
        rendered
    }
}

/// Intern `(callee, params -> ret)`, enqueueing the pair the first time it is
/// seen. Returns the emitted symbol, or the reason no symbol may exist.
///
/// The caps are checked here rather than at drain time because the drain is
/// downstream of the allocation this bounds: a signature that is already too
/// large has already been built.
pub(crate) fn intern_specialization(
    callee: &str,
    params: &[HostTypeTerm],
    ret: &HostTypeTerm,
) -> Result<String, MonoRejection> {
    let nodes = params
        .iter()
        .map(host_type_node_count)
        .sum::<usize>()
        .saturating_add(host_type_node_count(ret));
    let key = canonical_signature_key(params, ret);
    let label = format!("{callee}{key}");
    // An empty prefix is a fact, not a default: this call site is not inside
    // any specialization, so it IS the head of its instantiation chain.
    let mut chain = MONO_FRAMES.with(|frames| match frames.borrow().last() {
        Some(frame) => frame.chain.clone(),
        None => Vec::new(),
    });
    chain.push(label);

    if let Some(symbol) = MONO_INTERN.with(|intern| {
        intern
            .borrow()
            .get(&(callee.to_string(), key.clone()))
            .cloned()
    }) {
        return Ok(symbol);
    }
    if nodes > MONO_SIGNATURE_NODE_CAP {
        return Err(MonoRejection::UnboundedInstantiation {
            chain,
            reason: format!(
                "signature has {nodes} type nodes, over the \
                 {MONO_SIGNATURE_NODE_CAP}-node cap"
            ),
        });
    }
    let minted = MONO_SPECIALIZATION_COUNTS.with(|counts| {
        let mut counts = counts.borrow_mut();
        let slot = counts.entry(callee.to_string()).or_insert(0);
        *slot += 1;
        *slot
    });
    if minted > MONO_SPECIALIZATION_CAP {
        return Err(MonoRejection::UnboundedInstantiation {
            chain,
            reason: format!(
                "{minted} distinct specializations, over the \
                 {MONO_SPECIALIZATION_CAP}-per-callee cap"
            ),
        });
    }

    // The origin is the callee-qualified label, not the signature alone: two
    // DIFFERENT callees whose names sanitize to one C identifier (`A.f` and
    // `A_f`) would otherwise pass this check while sharing a symbol.
    let symbol = mono_symbol(callee, &key);
    let origin = format!("{callee}{key}");
    if let Some(existing) = MONO_SYMBOL_ORIGINS.with(|origins| {
        origins
            .borrow_mut()
            .insert(symbol.clone(), origin.clone())
            .filter(|existing| existing != &origin)
    }) {
        return Err(MonoRejection::SymbolCollision {
            symbol,
            signature: origin,
            existing,
        });
    }
    MONO_INTERN.with(|intern| {
        intern
            .borrow_mut()
            .insert((callee.to_string(), key), symbol.clone())
    });
    MONO_WORKLIST.with(|worklist| {
        worklist.borrow_mut().push_back(PendingSpecialization {
            callee: callee.to_string(),
            symbol: symbol.clone(),
            params: params.to_vec(),
            ret: ret.clone(),
            chain,
        })
    });
    Ok(symbol)
}

pub(crate) fn pop_pending_specialization() -> Option<PendingSpecialization> {
    MONO_WORKLIST.with(|worklist| worklist.borrow_mut().pop_front())
}

/// Push the type-variable environment for one specialization's body.
pub(crate) fn push_mono_frame(
    callee: &str,
    bindings: HashMap<String, HostTypeTerm>,
    chain: Vec<String>,
) {
    MONO_FRAMES.with(|frames| {
        frames.borrow_mut().push(MonoFrame {
            callee: callee.to_string(),
            bindings,
            chain,
        })
    });
}

pub(crate) fn pop_mono_frame() {
    MONO_FRAMES.with(|frames| {
        frames.borrow_mut().pop();
    });
}

/// The enclosing specialization's binding for `variable`, when the call being
/// lowered is a *self*-recursive call inside that specialization.
///
/// This is the one place a binding is read rather than derived from the call
/// site's own types, and it is deliberately narrow. Inside `f`'s body the
/// signature's type variables are rigid, so when a recursive `f(...)`
/// argument carries no checked type of its own — `loop(Empty)` in
/// chelis#941's reproducer, where `Empty` is a nullary constructor whose type
/// the checker solved by unifying it with `f`'s own parameter — the enclosing
/// instantiation *is* the checker's solution, not a guess. Restricting the
/// lookup to `callee == the def being specialized` keeps it from being
/// applied across two defs that happen to have both authored `[a]`.
pub(crate) fn enclosing_binding(callee: &str, variable: &str) -> Option<HostTypeTerm> {
    MONO_FRAMES.with(|frames| {
        let frames = frames.borrow();
        let frame = frames.last()?;
        (frame.callee == callee)
            .then(|| frame.bindings.get(variable).cloned())
            .flatten()
    })
}

