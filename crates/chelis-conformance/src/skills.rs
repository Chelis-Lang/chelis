/// The embedded `SKILL.md` for `name`, or `None` if `name` is not a shared skill.
pub fn skill_body(name: &str) -> Option<&'static str> {
    EMBEDDED_SKILLS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, body)| *body)
}
