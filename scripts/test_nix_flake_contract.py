    @REQUIRES_NIX
    def test_every_system_evaluates_without_import_from_derivation(self) -> None:
        # Negative control: this Nix enforces the option on a real IFD read.
        probe = subprocess.run(
            [
                NIX,
                "eval",
                "--impure",
                "--option",
                "allow-import-from-derivation",
                "false",
                "--expr",
                'builtins.readFile (derivation { name = "ifd-probe"; '
                'system = builtins.currentSystem; builder = "/bin/sh"; '
                'args = [ "-c" "echo 1 > $out" ]; })',
            ],
            cwd=REPO_ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        self.assertNotEqual(probe.returncode, 0)
        self.assertIn("allow-import-from-derivation", probe.stderr)
        for system in EXPECTED_SYSTEMS:
            for output in ("packages", "checks", "apps"):
                with self.subTest(system=system, output=output):
                    attribute = "program" if output == "apps" else "drvPath"
                    evaluated = nix_json(
                        "eval",
                        "--option",
                        "allow-import-from-derivation",
                        "false",
                        "--json",
                        f".#{output}.{system}",
                        "--apply",
                        f"builtins.mapAttrs (_name: value: value.{attribute})",
                    )
                    if output == "packages":
                        self.assertEqual(sorted(evaluated), EXPECTED_PACKAGES)
                    if output == "apps":
                        self.assertEqual(sorted(evaluated), EXPECTED_APPS)

