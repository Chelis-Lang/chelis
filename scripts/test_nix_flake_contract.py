    @REQUIRES_NIX
    def test_default_package_and_application_are_exact_native_aliases(self) -> None:
        system = nix_raw(
            "eval",
            "--impure",
            "--raw",
            "--expr",
            "builtins.currentSystem",
        )
        self.assertIn(system, EXPECTED_SYSTEMS)
        default_package = nix_raw(
            "eval", "--raw", f".#packages.{system}.default.drvPath"
        )
        chelis_package = nix_raw(
            "eval", "--raw", f".#packages.{system}.chelis.drvPath"
        )
        self.assertEqual(default_package, chelis_package)

        default_program = nix_raw(
            "eval", "--raw", f".#apps.{system}.default.program"
        )
        chelis_program = nix_raw(
            "eval", "--raw", f".#apps.{system}.chelis.program"
        )
        self.assertEqual(default_program, chelis_program)

    @REQUIRES_NIX
    def test_every_system_evaluates_without_import_from_derivation(self) -> None:
        # Negative control: this Nix enforces the option on a real IFD read.
        probe = subprocess.run(
            [
                NIX,
                "eval",
                "--impure",
                "--option",
                "allow-import-from-derivation",
                "false",
                "--expr",
                'builtins.readFile (derivation { name = "ifd-probe"; '
                'system = builtins.currentSystem; builder = "/bin/sh"; '
                'args = [ "-c" "echo 1 > $out" ]; })',
            ],
            cwd=REPO_ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        self.assertNotEqual(probe.returncode, 0)
        self.assertIn("allow-import-from-derivation", probe.stderr)
        for system in EXPECTED_SYSTEMS:
            for output in ("packages", "checks", "apps"):
                with self.subTest(system=system, output=output):
                    attribute = "program" if output == "apps" else "drvPath"
                    evaluated = nix_json(
                        "eval",
                        "--option",
                        "allow-import-from-derivation",
                        "false",
                        "--json",
                        f".#{output}.{system}",
                        "--apply",
                        f"builtins.mapAttrs (_name: value: value.{attribute})",
                    )
                    if output == "packages":
                        self.assertEqual(sorted(evaluated), EXPECTED_PACKAGES)
                    if output == "apps":
                        self.assertEqual(sorted(evaluated), EXPECTED_APPS)

